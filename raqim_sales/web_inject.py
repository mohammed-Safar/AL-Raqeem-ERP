# Banking translations: ERPNext's Banking page fetches frappe.translate.get_boot_translations, which
# this Frappe does not have, and then sets frappe._messages = {} (and its production build never
# uses boot.__messages either), so every text stayed English. This runs after the boot script and
# before the app starts: it uses the translations that already come with the page and ignores an
# empty overwrite (a real translation set from a later Frappe is still accepted).
# ROLLBACK: BANKING_I18N = False.
BANKING_I18N = True
BANKING_I18N_JS = (
	"<script>/* RAQEEM: Banking translations */(function(){try{if(!window.frappe||!frappe.boot)return;"
	"var m=frappe.boot.__messages||frappe._messages||{};"
	"Object.defineProperty(frappe,'_messages',{configurable:true,enumerable:true,"
	"get:function(){return m;},set:function(v){if(v&&Object.keys(v).length)m=v;}});"
	"}catch(e){}})();</script>"
)


def _is_app_page(path: str, base: str) -> bool:
	return path == base or (path.startswith(base + "/") and "." not in path.rsplit("/", 1)[-1])


def _is_crm_page(path: str) -> bool:
	return _is_app_page(path, "/crm")


# Arabic safety net (raqeem_spa_i18n.js) for the screens that run outside the desk:
# CRM, the HR app and the HR shift Roster. Only added when the user's language is Arabic.
# ROLLBACK: set SPA_I18N = False.
SPA_I18N = True
SPA_I18N_V = "3"  # bump when raqeem_spa_i18n.js changes
SPA_PAGES = ("/crm", "/hrms", "/hr", "/roster")


def _is_arabic() -> bool:
	return str(getattr(frappe.local, "lang", "") or "").startswith("ar")


def after_request(response=None, request=None):
	if response is None or request is None:
		return
	path = request.path or ""
	crm = _is_crm_page(path)
	hr = HR_SKIN and any(_is_app_page(path, p) for p in HR_PAGES)
	bank = BANKING_SKIN and _is_app_page(path, "/banking")
	spa = SPA_I18N and any(_is_app_page(path, p) for p in SPA_PAGES)
	if not (crm or hr or spa or bank):
		return
	if response.status_code != 200 or response.mimetype != "text/html" or response.direct_passthrough:
		return
	body = response.get_data(as_text=True)
	if "</head>" not in body:
		return
	head = ""
	if crm and "raqeem_crm.css" not in body:
		if CRM_EMBED and frappe.db.exists("Page", "raqeem-crm"):
			head += CRM_EMBED_JS  # first: it may move the page into the desk before anything loads
		head += CRM_HEAD
		if CRM_TOOLS:
			head += CRM_TOOLS_JS
		body = body.replace("<title>Frappe CRM</title>", "<title>RAQEEM CRM</title>", 1)
		if CRM_RTL and _is_arabic():
			body = body.replace('<html class="h-full" lang="en">', '<html class="h-full" lang="ar" dir="rtl">', 1)
	if hr and "raqeem_hrms.css" not in body:
		head += HR_HEAD
		body = body.replace("<title>Frappe HR</title>", "<title>RAQEEM HR</title>", 1)
		body = body.replace('content="Frappe HR"', 'content="RAQEEM HR"', 1)
		body = body.replace("<title>Roster</title>", "<title>RAQEEM HR · Roster</title>", 1)
	if bank and "raqeem_banking.css" not in body:
		head += BANKING_HEAD
		body = re.sub(r"<title>Banking \| [^<]*</title>", lambda m: f"<title>{frappe._('Banking')} · RAQEEM</title>", body, count=1)
		if BANKING_I18N and "</body>" in body:
			i = body.rindex("</body>")
			body = body[:i] + BANKING_I18N_JS + body[i:]
	# Arabic users: full safety net; everyone else: only the brand names (Frappe HR -> RAQEEM HR)
	if spa and "raqeem_spa_i18n.js" not in body:
		head += f"<script>window.__rq_ar={'true' if _is_arabic() else 'false'};</script>"
		head += (
			f'<script defer src="/assets/raqim_sales/js/raqeem_spa_keys.js?v={SPA_I18N_V}"></script>'
			f'<script defer src="/assets/raqim_sales/js/raqeem_spa_i18n.js?v={SPA_I18N_V}"></script>'
		)
	if not head:
		return
	response.set_data(body.replace("</head>", head + "</head>", 1))


@frappe.whitelist()
def spa_messages():
	"""All translations for the current user's language, for the Shift Roster screen,
	which does not receive them from its page (used by raqeem_spa_i18n.js)."""
	from frappe.translate import get_all_translations

	return get_all_translations(frappe.local.lang) if _is_arabic() else {}


@frappe.whitelist()
def crm_dock():
	"""The ERP rail exactly as this user sees it in the desk (same order, same hidden/permitted
	sections), for the dock that raqeem_crm_tools.js draws in CRM. The CRM tile is marked
	`current`; every other tile opens its desk section (/desk?rq_module=<name>, handled by
	raqeem_open_module.js with the desk's own navigation)."""
	from frappe.boot import get_module_sidebars
	from frappe.desk.doctype.dock.dock import resolve_dock

	permitted = set(get_module_sidebars().keys())
	entries = []
	for e in (resolve_dock() or {}).get("erpnext") or []:
		if e.get("hidden") or e.get("link_type") != "Sidebar" or e.get("link_to") not in permitted:
			continue
		name = e["link_to"]
		entries.append({"module": name, "icon": e.get("icon") or "", "label": frappe._(name), "current": name == "CRM"})
	user = frappe.get_cached_doc("User", frappe.session.user)
	return {
		"entries": entries,
		"user": {"name": user.full_name or user.name, "image": user.user_image or ""},
	}
