"""RAQEEM skin for the separate app screens (Frappe CRM at /crm).

CRM is its own single-page app: it does not load the desk's app_include_css, so the
RAQEEM theme never reaches it. Rather than edit CRM's files (which would be lost on
every CRM update), this after_request hook adds three things to the /crm HTML page
just before </head>:

  1. the RAQEEM fonts and raqeem_crm.css (generated by scripts/gen_crm_css.py from
     the desk theme, so the colours stay the same);
  2. a tiny inline script that runs BEFORE CRM starts: it reads the shared theme
     memory (localStorage raqeem_theme / raqeem_accent, the same keys the login page
     and the desk use) and hands it to CRM's own key ("theme": light/dark/system),
     then writes CRM's own light/dark switch back into the shared memory;
  3. the page title "RAQEEM CRM".

Safe by design: it only touches successful text/html responses for /crm, does
nothing if CRM is not installed, and Frappe catches any error from after_request
hooks (the page is then served unchanged).

ROLLBACK: remove the after_request line from hooks.py (then clear-cache).
"""

