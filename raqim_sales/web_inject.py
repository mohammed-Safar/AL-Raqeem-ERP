"""RAQEEM skin for the separate app screens (Frappe CRM at /crm).

CRM is its own single-page app: it does not load the desk's app_include_css, so the
RAQEEM theme never reaches it. Rather than edit CRM's files (which would be lost on
every CRM update), this after_request hook adds three things to the /crm HTML page
just before </head>:

  1. the RAQEEM fonts and raqeem_crm.css (generated by scripts/gen_crm_css.py from
     the desk theme, so the colours stay the same);
  2. a tiny inline script that runs BEFORE CRM starts: it reads the shared theme
     memory (localStorage raqeem_theme / raqeem_accent, the same keys the login page
     and the desk use) and hands it to CRM's own key ("theme": light/dark/system),
     then writes CRM's own light/dark switch back into the shared memory;
  3. the page title "RAQEEM CRM".

Safe by design: it only touches successful text/html responses for /crm, does
nothing if CRM is not installed, and Frappe catches any error from after_request
hooks (the page is then served unchanged).

ROLLBACK: remove the after_request line from hooks.py (then clear-cache).
"""

from __future__ import annotations

V = "1"  # bump when raqeem_crm.css or the script below changes

CRM_HEAD = (
	'<link rel="stylesheet" href="/assets/raqim_sales/css/raqeem_fonts.css?v=33">'
	f'<link rel="stylesheet" href="/assets/raqim_sales/css/raqeem_crm.css?v={V}">'
	"<script>/* RAQEEM: one theme memory for login, desk and CRM */"
	"(function(){try{"
	"var R=document.documentElement,L=localStorage,"
	"toCrm={light:'light',dark:'dark',auto:'system'},toRq={light:'light',dark:'dark',system:'auto'};"
	"var m=L.getItem('raqeem_theme');if(toCrm[m])L.setItem('theme',toCrm[m]);"
	"var a=L.getItem('raqeem_accent');if(a&&a!=='mono')R.setAttribute('data-accent',a);"
	"R.classList.add('rq-crm');"
	"function back(){setTimeout(function(){try{var t=toRq[L.getItem('theme')];if(t)L.setItem('raqeem_theme',t);}catch(e){}},0);}"
	"new MutationObserver(back).observe(R,{attributes:true,attributeFilter:['data-theme']});"
	"}catch(e){}})();</script>"
)


def _is_crm_page(path: str) -> bool:
	return path == "/crm" or (path.startswith("/crm/") and "." not in path.rsplit("/", 1)[-1])


def after_request(response=None, request=None):
	if response is None or request is None:
		return
	if not _is_crm_page(request.path or ""):
		return
	if response.status_code != 200 or response.mimetype != "text/html" or response.direct_passthrough:
		return
	body = response.get_data(as_text=True)
	if "raqeem_crm.css" in body or "</head>" not in body:
		return
	body = body.replace("</head>", CRM_HEAD + "</head>", 1)
	body = body.replace("<title>Frappe CRM</title>", "<title>RAQEEM CRM</title>", 1)
	response.set_data(body)
