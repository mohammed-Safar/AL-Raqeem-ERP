"""Build raqeem_portal.css: the desk's dark tokens + palette, scoped to the
website pages a logged-in user sees (portal, /me, web forms, error pages).
Print views and the public website for guests are left untouched.
Run after editing raqeem_theme.css tokens or regenerating raqeem_palette.css."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
CSS = os.path.join(HERE, "../raqim_sales/public/css")

SCOPE = ('body[frappe-session-status="logged-in"]:not([data-path^="printview"])'
         ':not([data-path^="printpreview"]):not([data-path="login"]):not([data-path="update-password"])')

def token_block(path, marker):
    s = open(os.path.join(CSS, path), encoding="utf-8").read()
    i = s.index(marker)
    j = s.index("{", i)
    k = s.index("}", j)
    return s[j + 1:k]

theme = open(os.path.join(CSS, "raqeem_theme.css"), encoding="utf-8").read()

def block_after(marker):
    """body of the first {...} block that follows marker"""
    i = theme.index(marker)
    j = theme.index("{", i)
    return theme[j + 1:theme.index("}", j)].strip()

rq_light = block_after("1. Design tokens")
k = theme.index("/* carbon dark */")
rq_dark = theme[k:theme.index("}", k)].strip()
fr_common = block_after("2a. both modes")
fr_light = block_after("2b. light")
fr_dark = block_after("2c. carbon dark")
pal = open(os.path.join(CSS, "raqeem_palette.css"), encoding="utf-8").read()
palette = pal[pal.index("{") + 1:pal.rindex("}")].strip()

# Website pages carry no data-theme, so they follow the device setting.
out = f"""/* ==========================================================================
   ALRAQEEM — PORTAL / WEBSITE PAGES FOR LOGGED-IN USERS (generated)
   Light by default, carbon dark when the device prefers dark.
   Generated by apps/raqim_sales/scripts/gen_portal_css.py — do not edit by hand.
   ========================================================================== */
{SCOPE} {{
    {rq_light}
    {fr_common}
    {fr_light}
}}
@media (prefers-color-scheme: dark) {{
{SCOPE} {{
    {rq_dark}
    {fr_dark}
    {palette}
}}
}}
"""
out += open(os.path.join(HERE, "portal_styles.css"), encoding="utf-8").read().replace("SCOPE", SCOPE)
open(os.path.join(CSS, "raqeem_portal.css"), "w", encoding="utf-8").write(out)
print("wrote raqeem_portal.css", len(out), "bytes")
