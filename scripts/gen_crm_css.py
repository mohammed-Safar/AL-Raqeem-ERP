"""Build raqim_sales/public/css/raqeem_crm.css — the RAQEEM skin for Frappe CRM (/crm).

It reuses the desk theme so CRM never drifts from it:
  * raqeem_theme.css sections 1 (design tokens), 1b (accent colour sets),
    2b (light Frappe variables) and 2c (carbon dark Frappe variables);
  * raqeem_palette.css (dark status colours);
  * scripts/crm_styles.css (CRM-only rules).

Re-run after editing any of those:  python3 apps/raqim_sales/scripts/gen_crm_css.py
then bump V in raqim_sales/web_inject.py so browsers fetch the new file.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CSS = os.path.join(HERE, "../raqim_sales/public/css")


def section(text, start_title, end_title):
    """Text from the comment block that holds start_title up to the one that holds end_title."""
    a = text.index(start_title)
    a = text.rindex("/*", 0, a)
    b = text.index(end_title, a)
    b = text.rindex("/*", 0, b)
    return text[a:b]


theme = open(os.path.join(CSS, "raqeem_theme.css"), encoding="utf-8").read()
parts = [
    "/* generated by scripts/gen_crm_css.py — do not edit by hand */",
    section(theme, "1. Design tokens", "2. Frappe variable overrides"),   # 1 + 1b
    section(theme, "2b. light:", "3. Base"),                            # 2b + 2c
    open(os.path.join(CSS, "raqeem_palette.css"), encoding="utf-8").read(),
    open(os.path.join(HERE, "crm_styles.css"), encoding="utf-8").read(),
]
out = "\n".join(parts)
for must in ("--rq-a-500", "--surface-gray-1", "html[data-theme=\"dark\"]", "rq-crm"):
    assert must in out, must
open(os.path.join(CSS, "raqeem_crm.css"), "w", encoding="utf-8").write(out)
print("raqeem_crm.css:", len(out.splitlines()), "lines")
