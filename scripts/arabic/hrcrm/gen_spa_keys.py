"""List the English texts written straight into the CRM / HR / Roster screens (not wrapped in __()),
including the shared frappe-ui library, and save them as public/js/raqeem_spa_keys.js.

raqeem_spa_i18n.js translates ONLY these texts on screen, so user data (a contact called "May")
is never touched. Re-run after updating CRM or HRMS:   python3 -I gen_spa_keys.py
Their Arabic must exist in ar.csv (check: the script prints the ones that have none).
"""
import csv, json, os, re

APPS = __import__('os').path.expanduser('~/')+"bench2/apps"
OUT = f"{APPS}/raqim_sales/raqim_sales/public/js/raqeem_spa_keys.js"
SOURCES = [
	f"{APPS}/crm/frontend/src",
	f"{APPS}/hrms/frontend/src",
	f"{APPS}/hrms/roster/src",
	f"{APPS}/crm/frontend/node_modules/frappe-ui/src",
	f"{APPS}/hrms/frontend/node_modules/frappe-ui/src",
]
ATTR = re.compile(r'''(?<![:@\w-])(label|placeholder|title|description|empty-text|emptyText|tooltip|message|heading|helpText|aria-label|button-label)="([^"{}]*[A-Za-z][^"{}]*)"''')
TEXT = re.compile(r">\s*([A-Za-z][^<>{}]*?[A-Za-z.!?:)])\s*<")
JSLAB = re.compile(r'''\b(label|placeholder|title|description|emptyText|message|text)\s*:\s*(['"`])([A-Z][^'"`$]{1,80})\2''')
JUNK = re.compile(r"Invalid state|Unknown state|@|https?://|\.(com|cloud|io|org)\b|^[A-Z0-9_]{6,}$|^\d|rem$|px$|slotProps|^[a-z]+[A-Z]\w*$|^[a-z0-9_\-]+$")

keys = set()
for base in SOURCES:
	for root, dirs, files in os.walk(base):
		dirs[:] = [d for d in dirs if d not in ("stories", "tests", "__tests__", "docs", "examples", "node_modules")]
		for f in files:
			if ".story." in f or ".test." in f or not f.endswith((".vue", ".js", ".ts")):
				continue
			t = open(os.path.join(root, f), encoding="utf-8", errors="ignore").read()
			m = re.search(r"<template>(.*)</template>", t, re.S)
			if m:
				tpl = re.sub(r"<svg.*?</svg>|<!--.*?-->", "", m.group(1), flags=re.S)
				keys.update(a.group(2).strip() for a in ATTR.finditer(tpl))
				keys.update(" ".join(n.group(1).split()) for n in TEXT.finditer(tpl))
			keys.update(a.group(3).strip() for a in JSLAB.finditer(t))
# 2) the COMPILED bundles (what the browser runs, including libraries the source scan cannot
#    see, e.g. CRM's onboarding/help panel): labels and printed text that are not wrapped in __()
COMPILED = [f"{APPS}/crm/crm/public/frontend/assets", f"{APPS}/hrms/hrms/public/frontend/assets", f"{APPS}/hrms/hrms/public/roster/assets"]
CRX = [r'(?<![\w.])label:`([^`$]{2,100})`', r'(?<![\w.])[A-Za-z]\(`([A-Z][^`$]{2,120})`\)',
       r'"aria-label":`([^`$]{2,80})`', r'(?<![\w.])title:`([A-Z][^`$]{2,100})`,(?:onClick|description|icon|variant)']
for d in COMPILED:
	for f in os.listdir(d) if os.path.isdir(d) else []:
		if not f.endswith(".js"):
			continue
		t = open(os.path.join(d, f), encoding="utf-8", errors="ignore").read()
		for rx in CRX:
			for m in re.finditer(rx, t):
				k = m.group(1).strip()
				if " " not in k and not k.endswith(("...", "…")):
					continue  # single CamelCase words here are component names, not text
				if ("__(`" + k + "`") not in t and re.search("[a-z]{2}", k):
					keys.add(k)
# 3) text the scans cannot see (built at run time); patterns live in raqeem_spa_i18n.js
keys.update(["Start now", "Continue", "Getting started", "Skip all", "Help centre", "RAQEEM CRM"])
keys = sorted(k for k in keys if k and not JUNK.search(k) and re.search("[A-Za-z]{2}", k) and len(k) < 300)

ar = {}
for r in csv.reader(open(f"{APPS}/raqim_sales/raqim_sales/translations/ar.csv", encoding="utf-8")):
	if r:
		ar[r[0].replace("\\n", "\n")] = r[1]
with open(OUT, "w", encoding="utf-8") as f:
	f.write("/* generated by scripts/arabic/hrcrm/gen_spa_keys.py: hard-coded English in CRM/HR screens */\n")
	f.write("window.RQ_SPA_KEYS = " + json.dumps(keys, ensure_ascii=False) + ";\n")
no_ar = [k for k in keys if k not in ar]
print(f"{len(keys)} keys -> {OUT}; without Arabic in ar.csv: {len(no_ar)}")
for k in no_ar[:40]:
	print("  NO AR:", k)
